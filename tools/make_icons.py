"""Writes src/reference_icons.hpp: Pocket Reference's icons as PNG bytes.

The icons are the SVGs of Pocket Reference's design mockup, kept here and
rasterised by rsvg-convert at 2x, so they are drawn at density 2. Run it
again after changing an icon; the header is checked in.
"""
import subprocess
from pathlib import Path

ICONS: dict[str, str] = {
    "root": '<rect x="2" y="1" width="11" height="14" rx="1" fill="#2f6db6"/><rect x="4" y="3" width="7" height="1.4" fill="#fff"/><rect x="4" y="6" width="7" height="1" fill="#cfe0f5"/><rect x="4" y="8" width="5" height="1" fill="#cfe0f5"/><rect x="12" y="2" width="2" height="12" fill="#e0aa45"/>',
    "book": '<path d="M2 2.5h5c.6 0 1 .4 1 1V14c0-.6-.4-1-1-1H2z" fill="#e8c46a" stroke="#9a6316" stroke-width=".8"/><path d="M14 2.5H9c-.6 0-1 .4-1 1V14c0-.6.4-1 1-1h5z" fill="#f3d98f" stroke="#9a6316" stroke-width=".8"/>',
    "control": '<rect x="1.5" y="3.5" width="13" height="9" rx="1.5" fill="#dbeafa" stroke="#336fb3"/><rect x="4" y="6.5" width="8" height="3" fill="#336fb3"/>',
    "type": '<path d="M8 1.5 14 5v6l-6 3.5L2 11V5z" fill="#f3e3c8" stroke="#9a6316"/><path d="M2 5l6 3.5L14 5M8 8.5v6" stroke="#9a6316" fill="none" stroke-width=".8"/>',
    "page": '<path d="M3 1.5h7l3 3v10H3z" fill="#fff" stroke="#5f7f9f"/><path d="M5 6h6M5 8.5h6M5 11h4" stroke="#2f6db6"/>',
    "back": '<path d="M9.5 2.5 4 8l5.5 5.5 1.4-1.4L6.8 8l4.1-4.1z" fill="#1d4f8c"/>',
    "forward": '<path d="M6.5 2.5 12 8l-5.5 5.5-1.4-1.4L9.2 8 5.1 3.9z" fill="#1d4f8c"/>',
    "home": '<path d="M8 1.8 1.5 7.5h1.8V14h3.6v-4h2.2v4h3.6V7.5h1.8z" fill="#2f6db6" stroke="#1b3970" stroke-width=".6"/>',
    "find": '<circle cx="6.5" cy="6.5" r="4.2" fill="#eaf3fd" stroke="#1d4f8c" stroke-width="1.6"/><path d="M9.6 9.6 14 14" stroke="#1d4f8c" stroke-width="2.2"/>',
}


def main() -> int:
    here: Path = Path(__file__).resolve().parents[1]
    lines: list[str] = [
        "// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0",
        "#pragma once",
        "// Generated by tools/make_icons.py from the mockup's SVGs; do not edit.",
        "// Each icon is a 32-pixel PNG, drawn at density 2 (16 units).",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace pocket_reference::icons {",
        "",
    ]
    for name, body in ICONS.items():
        svg: str = f'<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16">{body}</svg>'
        png: bytes = subprocess.run(["rsvg-convert", "-w", "32", "-h", "32", "-f", "png"], input=svg.encode(),
                                    capture_output=True, check=True).stdout
        lines.append(f"inline constexpr std::array<std::uint8_t, {len(png)}> {name}_png{{{{")
        for start in range(0, len(png), 20):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in png[start:start + 20]) + ",")
        lines.append("}};")
        lines.append("")
    lines.append("} // namespace pocket_reference::icons")
    (here / "src/reference_icons.hpp").write_text("\n".join(lines) + "\n")
    print(f"{len(ICONS)} icons")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
